#include <beet_math/vec3.h>

//===API================================================================================================================
float vec3f_dot(const vec3f& a, const vec3f& b) {
    return a.x * b.x + a.y * b.y + a.z * b.z;
}

float vec3f_sq(const vec3f& a) {
    return vec3f_dot(a, a);
}
